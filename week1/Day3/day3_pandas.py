df['Name'] = df['Name'].str.replace('LÃ¼deritz', 'Lüderitz', regex=False)

# Cleaning 'Launch Year' (Convert empty strings/spaces to actual NaN, then convert to numeric/nullable integer)
df['Launch Year'] = pd.to_numeric(df['Launch Year'].replace('', pd.NA), errors='coerce').astype('Int64')

# Handling Missing Values in Categorical Columns (Replacing empty class/country with 'Unknown')
df['Class'] = df['Class'].fillna('Unknown')
df['Country'] = df['Country'].fillna('Unknown')

# Removing all Duplicates
df = df.drop_duplicates()
