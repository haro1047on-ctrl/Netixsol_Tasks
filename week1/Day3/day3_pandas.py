print(top_3_countries)

# excluding 'No Classification'
for country in top_3_countries:
    country_df = df[df['Country'] == country]

    filtered_classes = country_df['Class'][country_df['Class'] != 'No Classification']

    if not filtered_classes.empty:
        most_common_class = filtered_classes.value_counts().idxmax()
        count_of_class = filtered_classes.value_counts().max()
        print(f"The most common ship class for {country} is '{most_common_class}' with {count_of_class} units.\n")
    else:
        print(f"No other classified ships found for {country} besides 'No Classification'.\n")

